// Single source of truth: web/wp-content/themes/chargenet/tokens.json.
// Generates assets/src/scss/_tokens.generated.scss (CSS custom properties) and _breakpoints.generated.scss ($breakpoints)
// and mirrors the tokens into theme.json. Fails if a contrast pair is below its target.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const theme = resolve(import.meta.dirname, '../web/wp-content/themes/chargenet');
const t = JSON.parse(readFileSync(resolve(theme, 'tokens.json'), 'utf8'));

const round = (n) => Number(n.toFixed(4));
const title = (slug) => slug.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase());

// Contrast check (WCAG 2.x relative luminance).
const lum = (hex) => {
	const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
	const [r, g, b] = c.map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
	return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
	const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
	return (hi + 0.05) / (lo + 0.05);
};
const failures = t.contrast.filter(([fg, bg, min]) => ratio(t.colors[fg], t.colors[bg]) < min);
if (failures.length) {
	console.error(
		'Contrast failures:',
		failures.map(([fg, bg, min]) => `${fg} on ${bg} < ${min}`),
	);
	process.exit(1);
}

// Fluid interpolation between two viewports (Utopia method), values in rem.
const { minViewport: v0, maxViewport: v1 } = t.type;
const fluid = (minRem, maxRem) => {
	const slope = (maxRem - minRem) / ((v1 - v0) / 16);
	const base = minRem - slope * (v0 / 16);
	return `clamp(${round(minRem)}rem, ${round(base)}rem + ${round(slope * 100)}vw, ${round(maxRem)}rem)`;
};
const typeSizes = Object.fromEntries(
	Object.entries(t.type.steps).map(([name, i]) => [
		name,
		fluid(
			(t.type.minBase * t.type.minRatio ** i) / 16,
			(t.type.maxBase * t.type.maxRatio ** i) / 16,
		),
	]),
);
const fluidSpace = Object.fromEntries(
	Object.entries(t.fluidSpacing).map(([k, [a, b]]) => [k, fluid(a, b)]),
);

const vars = [];
const add = (prefix, obj) =>
	Object.entries(obj).forEach(([k, v]) => vars.push(`--${prefix}-${k}: ${v};`));
add('color', t.colors);
add('font', t.fontFamily);
add('text', typeSizes);
add('leading', t.lineHeight);
add('weight', t.weight);
add('space', t.spacing);
add('space', fluidSpace);
add('container', t.container);
add('radius', t.radius);
add('shadow', t.shadow);
add('duration', t.motion.duration);
add('ease', t.motion.ease);
add('distance', t.motion.distance);

const bps = Object.entries(t.breakpoints)
	.map(([k, v]) => `\t${k}: ${v},`)
	.join('\n');
const scss = resolve(theme, 'assets/src/scss');
writeFileSync(
	resolve(scss, '_breakpoints.generated.scss'),
	`// GENERATED by bin/build-tokens.mjs from tokens.json. Do not edit.\n$breakpoints: (\n${bps}\n);\n`,
);
writeFileSync(
	resolve(scss, '_tokens.generated.scss'),
	`// GENERATED by bin/build-tokens.mjs from tokens.json. Do not edit.\n:root {\n${vars.map((v) => `\t${v}`).join('\n')}\n}\n`,
);

// Mirror into theme.json.
const file = resolve(theme, 'theme.json');
const json = JSON.parse(readFileSync(file, 'utf8'));
const s = json.settings;
s.layout = { contentSize: t.container.narrow, wideSize: t.container.default };
s.color.palette = Object.entries(t.colors).map(([slug, color]) => ({
	slug,
	name: title(slug),
	color,
}));
s.typography.fontFamilies = [
	{ slug: 'sans', name: 'Source Sans 3', fontFamily: t.fontFamily.sans },
];
s.typography.fontSizes = Object.entries(typeSizes).map(([slug, size]) => ({
	slug,
	name: slug,
	size,
	fluid: false,
}));
s.spacing = {
	spacingScale: { steps: 0 },
	spacingSizes: [...Object.entries(t.spacing), ...Object.entries(fluidSpace)].map(
		([slug, size]) => ({ slug, name: slug, size }),
	),
};
s.shadow = {
	defaultPresets: false,
	presets: Object.entries(t.shadow).map(([slug, shadow]) => ({ slug, name: slug, shadow })),
};
s.custom = {
	radius: t.radius,
	duration: t.motion.duration,
	ease: t.motion.ease,
	distance: t.motion.distance,
	breakpoint: t.breakpoints,
};
json.styles = {
	color: {
		text: 'var(--wp--preset--color--ink-900)',
		background: 'var(--wp--preset--color--white)',
	},
	typography: { fontFamily: 'var(--wp--preset--font-family--sans)', lineHeight: t.lineHeight.body },
};
writeFileSync(file, `${JSON.stringify(json, null, '\t')}\n`);
console.log('Tokens built.');
